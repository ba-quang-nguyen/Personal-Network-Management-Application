function t(key, vars) {
  let s = (STR.en && STR.en[key]) || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.split("{" + k + "}").join(vars[k]);
    });
  }
  return s;
}

function applyStaticI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.getAttribute("data-i18n")); });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph"))); });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => { el.setAttribute("title", t(el.getAttribute("data-i18n-title"))); });
}

/* display label for a stored relationship-type string (fallback: raw value) */
function relTypeLabel(v) {
  const map = {
    "Key contact": "rel_key", "Client": "rel_client", "Partner": "rel_partner", "Investor": "rel_investor",
    "Mentor": "rel_mentor", "Friend": "rel_friend", "Collaborator": "rel_collaborator",
    "Acquaintance": "rel_acquaintance", "New": "rel_new"
  };
  return map[v] ? t(map[v]) : v;
}

